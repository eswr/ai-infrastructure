#!/usr/bin/env python3
"""prefix_cache.py — phase-4B cold vs warm prefix-reuse study.

Question: how much latency does prefix caching save, under what
concurrency, and is the worker still healthy afterwards?

For each concurrency c in {1, 4, 8} and cache state in {cold, warm}:

    reset_cache (process restart — the one honest reset everywhere)
      -> wait_functional (real-generation probe; the 4D gate)
      -> [warm] fire 8 concurrent loadgen requests carrying the shared
         prefix so every llama.cpp slot holds it (slot-local caches)
      -> measured run: 8 requests x (8192 shared + 128 unique) nominal
         tokens, out=256, burst, streaming, through the gateway
      -> post-run functional probe + gateway lifecycle verdict
      -> teardown

Warm requests are generated by loadgen itself with the same scenario
seed — the shared prefix words must be byte-identical to the measured
ones, and Python cannot reproduce the Rust StdRng sequence.

Artifacts: <out>/<leg>/<study>-<ts>/matrix.json (+records), a study
lifecycle.json (cache methods, per-leg verdicts), and a 1 Hz memory.csv
(vmmap footprint — RSS lies on unified memory). Run cache_econ.py on the
study dir afterwards.

Usage:
    python3 benchmarks/prefix_cache.py --runtime llama-cpp \
        --out benchmarks/results [--cs 1,4,8] [--gateway PATH]
Stdlib only.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from runtime_harness import (  # noqa: E402
    FUNCTIONAL_TIMEOUT_S,
    LIVE_TIMEOUT_S,
    MemorySampler,
    http_get,
    kill_leftovers,
    log,
    make_runtime,
)

REPO = Path(__file__).resolve().parent.parent

SHARED_TOKENS = 8192
UNIQUE_TOKENS = 128
OUTPUT_TOKENS = 256
NUM_REQUESTS = 8
SEED = 42


def write_leg_matrix(path: Path, leg: str, c: int, worker_endpoint: str,
                     gateway_endpoint: str, model: str, warm: bool,
                     out_tokens: int) -> None:
    """One matrix = one loadgen invocation. Warm legs prepend a warmup run
    that populates every slot's cache direct-to-worker (endpoint override)
    with the SAME seed as the measured run — byte-identical shared prefix
    (Python cannot reproduce the Rust StdRng word sequence, so the warm
    requests must come from the same generator)."""
    warm_block = ""
    if warm:
        warm_block = f"""
# Cache population: same seed -> byte-identical shared prefix as the
# measured run, fired concurrently so every slot caches it.
[[warmup]]
name = "populate"
endpoint = "{worker_endpoint}"
input_tokens = {SHARED_TOKENS + UNIQUE_TOKENS}
concurrency = {NUM_REQUESTS}
num_requests = {NUM_REQUESTS}
shared_prefix_tokens = {SHARED_TOKENS}
output_tokens = 4
"""
    path.write_text(f"""
study = "prefix-cache-{leg}"
description = "phase-4B {leg}: shared {SHARED_TOKENS}t prefix + {UNIQUE_TOKENS}t suffix, out={out_tokens}"
cooldown_s = 2.0
{warm_block}
[defaults]
endpoint = "{gateway_endpoint}"
model = "{model}"
output_tokens = {out_tokens}
stream = true
arrival = "burst"
timeout_s = 900
seed = {SEED}
shared_prefix_tokens = {SHARED_TOKENS}

[[runs]]
name = "{leg}"
input_tokens = {SHARED_TOKENS + UNIQUE_TOKENS}
concurrency = {c}
num_requests = {NUM_REQUESTS}
""")


def wait_gateway_ready(gateway: subprocess.Popen, timeout_s: float = 60.0) -> dict:
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        if gateway.poll() is not None:
            raise RuntimeError("gateway exited during startup")
        if http_get("http://127.0.0.1:8080/healthz")[0] == 200:
            status, body = http_get("http://127.0.0.1:8080/status")
            if status == 200:
                try:
                    w0 = json.loads(body)["workers"][0]
                    if w0["state"] == "ready":
                        return w0
                except (KeyError, json.JSONDecodeError):
                    pass
        time.sleep(0.3)
    raise RuntimeError("gateway worker never reached READY")


def gateway_worker_state() -> dict:
    status, body = http_get("http://127.0.0.1:8080/status")
    if status != 200:
        return {"available": False}
    try:
        w0 = json.loads(body)["workers"][0]
        return {"state": w0["state"], "reason": w0.get("state_reason"),
                "generation": w0["generation"],
                "dimensions": w0.get("dimensions")}
    except (KeyError, json.JSONDecodeError):
        return {"available": False}


def run_leg(rt, gateway_bin: Path, study_dir: Path, leg: str, c: int,
            warm: bool, sampler: MemorySampler) -> dict:
    """One leg: reset -> functional gate -> [populate] -> measured run ->
    post-run health verdict. Returns the leg record."""
    leg_dir = study_dir / leg
    leg_dir.mkdir(parents=True, exist_ok=True)
    record: dict = {"leg": leg, "c": c, "state": "warm" if warm else "cold"}

    # -- reset: process restart IS the cache reset ---------------------------
    sampler.phase = "reset"
    if not rt.reset_cache():
        record["verdict"] = "restart_failed"
        return record
    probe = rt.wait_functional(FUNCTIONAL_TIMEOUT_S)
    record["post_reset_probe"] = {"ok": probe.ok, "tokens": probe.tokens,
                                  "error": probe.error}
    if not probe.ok:
        record["verdict"] = "not_functional_after_reset"
        return record

    model = rt.model
    sampler.phase = "idle"

    with (leg_dir / "gateway.log").open("wb") as gw_log:
        gw_env = {
            **os.environ,
            "GATEWAY_ADDR": "127.0.0.1:8080",
            "WORKERS": f"llama=http://127.0.0.1:{rt.port}#{model}",
            "ROUTE_POLICY": "lor",
            "FIRST_TOKEN_TIMEOUT_S": "900",
            # Steady-state probes are GPU work; keep measured runs quiet.
            "FUNCTIONAL_PROBE_INTERVAL_READY_S": "0",
            "HEALTH_INTERVAL_S": "2",
            "FUNCTIONAL_PROBE_INTERVAL_S": "2",
        }
        gw = subprocess.Popen([str(gateway_bin)], stdout=gw_log,
                              stderr=subprocess.STDOUT, env=gw_env, cwd=REPO,
                              start_new_session=True)
        try:
            w0 = wait_gateway_ready(gw)
            record["gateway_at_start"] = {"state": w0["state"],
                                          "generation": w0["generation"]}

            # One invocation: warm legs populate every slot first (warmup
            # run, direct-to-worker), then the measured run fires.
            sampler.phase = leg
            write_leg_matrix(leg_dir / "leg.toml", leg, c,
                             f"http://127.0.0.1:{rt.port}", "http://127.0.0.1:8080",
                             model, warm=warm, out_tokens=OUTPUT_TOKENS)
            t0 = time.time()
            rc = subprocess.run(
                [str(gateway_bin.parent / "loadgen"), "--matrix",
                 str(leg_dir / "leg.toml"), "--out-dir", str(leg_dir)],
                cwd=REPO, capture_output=True, text=True)
            record["run_exit"] = rc.returncode
            record["run_wall_s"] = round(time.time() - t0, 1)
            if rc.returncode != 0:
                (leg_dir / "run.log").write_text(rc.stdout[-4000:] + rc.stderr[-4000:])
            time.sleep(2)

            # -- the 4D cross-check: is the worker still healthy? ---------------
            sampler.phase = "post_probe"
            post = rt.functional_probe(phase=f"post_{leg}")
            record["post_run_probe"] = {"ok": post.ok, "tokens": post.tokens,
                                        "error": post.error,
                                        "total_ms": post.total_ms}
            record["gateway_after"] = gateway_worker_state()
            record["verdict"] = ("healthy" if post.ok and record["run_exit"] == 0
                                 else "degraded")
        finally:
            if gw.poll() is None:
                os.killpg(gw.pid, 15)
                try:
                    gw.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    os.killpg(gw.pid, 9)
    return record


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runtime", default="llama-cpp",
                    choices=["llama-cpp", "mlx-lm", "vllm-metal"])
    ap.add_argument("--cs", default="1,4,8", help="concurrency list, e.g. 1,4,8")
    ap.add_argument("--out", type=Path, default=REPO / "benchmarks/results")
    ap.add_argument("--gateway", type=Path, default=REPO / "target/release/gateway")
    ap.add_argument("--study-name", default="prefix-cache-reuse")
    ap.add_argument("--smoke", action="store_true",
                    help="tiny workload (1K prefix, 4 requests, out=32) to "
                         "validate the pipeline; not comparable data")
    args = ap.parse_args()

    global SHARED_TOKENS, OUTPUT_TOKENS, NUM_REQUESTS
    if args.smoke:
        SHARED_TOKENS, OUTPUT_TOKENS, NUM_REQUESTS = 1024, 32, 4

    if not args.gateway.exists():
        sys.exit("gateway binary missing — cargo build --release -p gateway")
    cs = [int(x) for x in args.cs.split(",")]

    ts = time.strftime("%Y%m%d-%H%M%S")
    study_dir = args.out / f"{args.study_name}-{ts}"
    study_dir.mkdir(parents=True)
    print(f"study dir: {study_dir}")

    rt = make_runtime(args.runtime)
    legs: list[dict] = []
    sampler = MemorySampler(lambda: rt.proc.pid if rt.proc else None,
                            study_dir / "memory.csv")
    sampler.start()
    try:
        kill_leftovers(rt.name)
        rt.start(study_dir / "runtime.log")
        if not rt.wait_live(LIVE_TIMEOUT_S):
            sys.exit(f"{rt.name} never went live")
        time.sleep(2)
        sampler.phase = "after_load"

        for c in cs:
            for state in ("cold", "warm"):
                leg = f"{state}-c{c}"
                log(f"=== leg {leg}")
                rec = run_leg(rt, args.gateway, study_dir, leg, c,
                              warm=(state == "warm"), sampler=sampler)
                legs.append(rec)
                log(f"=== leg {leg}: {rec.get('verdict')} "
                    f"(exit={rec.get('run_exit')}, wall={rec.get('run_wall_s')}s)")
    finally:
        rt.stop()
        sampler.stop()
        lifecycle = {
            "study": args.study_name,
            "created": ts,
            "runtime": rt.name,
            "model": rt.model,
            "workload": {
                "shared_prefix_tokens": SHARED_TOKENS,
                "unique_suffix_tokens": UNIQUE_TOKENS,
                "output_tokens": OUTPUT_TOKENS,
                "num_requests": NUM_REQUESTS,
                "seed": SEED,
                "stream": True,
                "arrival": "burst",
                "via_gateway": True,
            },
            "cache_reset_method": rt.cache_reset_method(),
            "cache_warm_method": (
                "loadgen warmup run, concurrency=8, out=4, direct-to-worker; "
                "same seed as measured runs so the shared prefix is "
                "byte-identical (Rust StdRng prefix synthesis)"
            ),
            "legs": legs,
            "memory_peak_rss_mb": round(sampler.peak_rss_mb, 1),
            "memory_peak_footprint_mb": round(sampler.peak_footprint_mb, 1),
        }
        (study_dir / "lifecycle.json").write_text(json.dumps(lifecycle, indent=2))
        log(f"lifecycle written: {study_dir / 'lifecycle.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
